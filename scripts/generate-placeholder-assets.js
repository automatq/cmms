#!/usr/bin/env node
/**
 * Generates solid-color PNG placeholder assets for apps/mobile/assets/.
 * No external deps — emits PNG bytes directly using zlib.
 *
 * REPLACE THESE FILES with real branding before App Store / Play Store
 * submission. They exist only so Expo's bundler can resolve the references
 * in app.json during development.
 */

const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

// MainTek brand color: #2563eb (Tailwind blue-600)
const BRAND = { r: 0x25, g: 0x63, b: 0xeb, a: 0xff };
const WHITE = { r: 0xff, g: 0xff, b: 0xff, a: 0xff };

const targets = [
  { name: 'icon.png', w: 1024, h: 1024, bg: BRAND, mark: WHITE },
  { name: 'splash.png', w: 1242, h: 2436, bg: BRAND, mark: WHITE },
  { name: 'adaptive-icon.png', w: 1024, h: 1024, bg: BRAND, mark: WHITE },
  { name: 'favicon.png', w: 48, h: 48, bg: BRAND, mark: WHITE },
  { name: 'notification-icon.png', w: 96, h: 96, bg: WHITE, mark: BRAND, monochrome: true },
];

function crc32(buf) {
  const table = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c >>> 0;
  }
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = (c >>> 8) ^ table[(c ^ buf[i]) & 0xff];
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length, 0);
  const typeBuf = Buffer.from(type, 'ascii');
  const crcBuf = Buffer.alloc(4);
  crcBuf.writeUInt32BE(crc32(Buffer.concat([typeBuf, data])), 0);
  return Buffer.concat([len, typeBuf, data, crcBuf]);
}

function makePng(width, height, bg, mark) {
  // Filter byte (0 = none) at the start of each scanline + RGBA pixels
  const bytesPerRow = 1 + width * 4;
  const raw = Buffer.alloc(bytesPerRow * height);
  // Draw a simple cross/wrench-like mark in the center for visual recognition
  // (so different placeholders look distinct rather than uniform fill).
  const cx = width / 2;
  const cy = height / 2;
  const armW = Math.max(2, Math.floor(width * 0.08));
  const armH = Math.max(2, Math.floor(height * 0.45));
  for (let y = 0; y < height; y++) {
    raw[y * bytesPerRow] = 0; // filter type none
    for (let x = 0; x < width; x++) {
      const inMark =
        (Math.abs(x - cx) <= armW / 2 && Math.abs(y - cy) <= armH / 2) ||
        (Math.abs(y - cy) <= armW / 2 && Math.abs(x - cx) <= armH / 2);
      const c = inMark ? mark : bg;
      const off = y * bytesPerRow + 1 + x * 4;
      raw[off] = c.r;
      raw[off + 1] = c.g;
      raw[off + 2] = c.b;
      raw[off + 3] = c.a;
    }
  }

  const sig = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;   // bit depth
  ihdr[9] = 6;   // color type RGBA
  ihdr[10] = 0;  // compression
  ihdr[11] = 0;  // filter
  ihdr[12] = 0;  // interlace
  const idat = zlib.deflateSync(raw);
  return Buffer.concat([
    sig,
    chunk('IHDR', ihdr),
    chunk('IDAT', idat),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

const outDir = path.resolve(__dirname, '..', 'apps', 'mobile', 'assets');
fs.mkdirSync(outDir, { recursive: true });

for (const t of targets) {
  const buf = makePng(t.w, t.h, t.bg, t.mark);
  const filePath = path.join(outDir, t.name);
  fs.writeFileSync(filePath, buf);
  console.log(`wrote ${path.relative(process.cwd(), filePath)} (${t.w}x${t.h}, ${buf.length} bytes)`);
}

const readme = `# Mobile Branding Assets — PLACEHOLDERS

These PNGs are generated by \`scripts/generate-placeholder-assets.js\` and
exist solely so Expo's bundler can resolve the references in
\`apps/mobile/app.json\` during development.

**Replace these with real branding before App Store / Play Store submission.**

## Required sizes

| File | Size | Used for |
|---|---|---|
| icon.png | 1024×1024 | App icon (all platforms) |
| splash.png | 1242×2436 | Launch splash (iOS reference; Expo down-scales) |
| adaptive-icon.png | 1024×1024 | Android adaptive icon foreground |
| favicon.png | 48×48 | Web favicon |
| notification-icon.png | 96×96 monochrome | Android notification tray icon |

## Notes

- \`notification-icon.png\` MUST be monochrome (white pixels on transparent background) for Android. The current placeholder is approximate.
- \`adaptive-icon.png\` should leave the outer ~33% as safe-zone padding so Android's circular/squircle masks don't crop the logo.
- Keep the filenames identical when replacing; \`app.json\` references them by relative path.

## To regenerate placeholders

\`\`\`
node scripts/generate-placeholder-assets.js
\`\`\`
`;

fs.writeFileSync(path.join(outDir, 'README.md'), readme);
console.log('wrote', path.relative(process.cwd(), path.join(outDir, 'README.md')));
